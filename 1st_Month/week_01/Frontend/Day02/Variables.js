// Variables 

// A variable is a container used to store data or values in JavaScript.

let name = "Rahul";
let age = 20;

console.log(name);
console.log(age);

//  let , const , var

// var allows redeclaration:

var age = 20;

var age = 25;

console.log(age);

// let -->  It allows changing the value of a variable.

let age = 18;

age = 19;

console.log(age);

// let cannot be redeclared in the same scope:
// let follows block scope:

// const --> const is used for values that should not be changed.

const pi = 3.14;

console.log(pi);



