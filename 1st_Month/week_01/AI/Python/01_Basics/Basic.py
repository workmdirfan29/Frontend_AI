# Python Basics
# This file explains variables, data types, operators, and input/output.


# 1. Variables:
# A variable is a container used to store data or values.

name = "Rahul"
age = 20

print(name)
print(age)



# 2. Data Types:
# Data types define what type of data is stored in a variable.

text = "Python"       # String (text value)
number = 100          # Integer (whole number)
decimal = 10.5        # Float (decimal number)
check = True          # Boolean (True or False)

print(text)
print(number)
print(decimal)
print(check)



# 3. Operators:
# Operators are symbols used to perform operations on values.

a = 10
b = 5

print(a + b)   # Addition
print(a - b)   # Subtraction
print(a * b)   # Multiplication
print(a / b)   # Division
print(a % b)   # Modulus (remainder)

print(a > b)   # Comparison Operator (True)



# 4. Input and Output:
# Input is used to take data from the user, and print() is used to display output.

user_name = input("Enter your name: ")

print("Hello", user_name)